print("Promedio de 4 calificaciones")
#Entrada calf1, calf2, calf3, calf4, prom
#Proceso (calf1+calf2+calf3+calf4)/4
#Salida prom

#Entrada
calf1=(int(input("Indique la calificación 1: ")))
calf2=(int(input("Indique la calificación 2: ")))
calf3=(int(input("Indique la calificación 3: ")))
calf4=(int(input("Indique la calificación 4: ")))
#Proceso
prom=(calf1+calf2+calf3+calf4)/4
#Salida
print(f"Su promedio de las 4 calificaciones: {prom:.2f}")