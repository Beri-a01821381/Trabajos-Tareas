print("Distancia recorrida por un caracol")
#Entrada minutos, distancia
#Proceso (minutos*60)/100
#Salida total

#Entrada
minutos=float(input("Indique cuantos minutos vio recorrer el caracol: "))
#Proceso 
distancia=((minutos*60)*5.7)/100
#Salida
print(f"La distancia total recorrida fue = {distancia:.2f}")